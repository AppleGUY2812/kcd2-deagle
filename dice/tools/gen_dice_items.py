#!/usr/bin/env python3
"""Writes dice/src/Scripts/DiceAdvisor/dice_items.lua: every die item of the game (item class id -> English name,
side weights, joker), so Lua can list the dice in the player's inventory. Reads Libs/Tables/item/item.xml from the
game's Tables.pak (one member, never the whole pak) and the English names from tools/farkle/dice_game.csv.
usage: gen_dice_items.py [game folder]"""
import csv, re, sys, zipfile
from pathlib import Path

repo = Path(__file__).resolve().parents[2]
game = Path(sys.argv[1] if len(sys.argv) > 1 else "/mnt/d/steam_bruh/steamapps/common/KingdomComeDeliverance2")
with zipfile.ZipFile(game / "Data" / "Tables.pak") as z:
    member = next(n for n in z.namelist() if n.lower().endswith("item/item.xml"))
    xml = z.read(member).decode("utf-8", "replace")
names = {r["internal_id"]: r["name"] for r in csv.DictReader(open(repo / "tools/farkle/dice_game.csv", encoding="utf-8"))}
attr = lambda tag, k: (re.search(r'\b' + k + r'="([^"]*)"', tag) or [None, ""])[1]
rows = []
for m in re.finditer(r"<Die\b[^>]*>", xml):
    tag = m.group(0)
    gid, internal = attr(tag, "Id").lower(), attr(tag, "Name").strip()
    weights = attr(tag, "SideWeights").split()
    values = attr(tag, "SideValues").split()
    if not gid or len(weights) != 6:
        continue
    joker = "1" if values[:1] == ["6"] else "0"   # SideValues 6 = joker; the game's jokers are all on face 1
    rows.append((gid, names.get(internal, internal), " ".join(weights), joker))
out = repo / "dice/src/Scripts/DiceAdvisor/dice_items.lua"
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- Generated by dice/tools/gen_dice_items.py from the game's item.xml (WHGame 1.5.6). Don't edit.\n")
    f.write("-- item class id -> { n = English name, w = side weights 1..6, j = 1 if face 1 is a joker }\n")
    f.write("DiceAdvisorItems = {\n")
    for gid, name, w, j in sorted(rows, key=lambda r: r[1]):
        f.write('\t["%s"] = { n = "%s", w = "%s", j = %s },\n' % (gid, name.replace('"', ""), w, j))
    f.write("}\n")
print(f"{len(rows)} dice -> {out.relative_to(repo)}")
