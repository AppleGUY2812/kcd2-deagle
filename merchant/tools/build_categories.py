#!/usr/bin/env python3
"""Writes merchant/src/Scripts/MerchantResale/categories.lua: item class GUID -> resale category, read from the game's
own item tables (Data/Tables.pak, Libs/Tables/item/item*.xml). Only weapon / armor / food / alchemy are listed; every
other class (and any item a mod adds) counts as misc. Usage: build_categories.py <game dir> <out.lua>"""
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

# element tag in item*.xml -> category (tags seen in 1.5.6: MeleeWeapon, MissileWeapon, Ammo, Armor, Hood, Helmet,
# Food, Herb, Alchemy..., Poison, Document, MiscItem, Key, ...). Unknown tags fall to misc.
RULES = [
    (re.compile(r"^(MeleeWeapon|MissileWeapon|Ammo|Weapon.*)$"), "weapon"),
    (re.compile(r"^(Armor|Hood|Helmet|Shield|Clothing.*)$"), "armor"),
    (re.compile(r"^(Food|Drink.*)$"), "food"),
    (re.compile(r"^(Herb|Alchemy.*|Potion.*|Poison.*|Ointment.*)$"), "alchemy"),
]


def category(tag):
    for rx, cat in RULES:
        if rx.match(tag):
            return cat
    return None


def main():
    game, out = sys.argv[1], sys.argv[2]
    pak = zipfile.ZipFile(f"{game}/Data/Tables.pak")
    names = sorted(n for n in pak.namelist() if re.match(r"Libs/Tables/item/item(__[^/]*)?\.xml$", n))
    cats, tags = {}, {}
    for name in names:
        root = ET.fromstring(pak.read(name))
        for el in root.iter():
            guid = el.get("Id")
            if not guid or not el.get("Name"):
                continue
            tags[el.tag] = tags.get(el.tag, 0) + 1
            cat = category(el.tag)
            if cat:
                cats[guid.lower()] = cat
    lines = ["-- generated by merchant/tools/build_categories.py from the game's item tables; do not edit",
             "MerchantResaleCategories = {"]
    for guid in sorted(cats):
        lines.append(f'["{guid}"]="{cats[guid]}",')
    lines.append("}")
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    counts = {}
    for c in cats.values():
        counts[c] = counts.get(c, 0) + 1
    print(f"{len(names)} tables, {sum(tags.values())} items; listed {len(cats)}: {counts}")
    print("tags:", ", ".join(f"{t}={n}" for t, n in sorted(tags.items(), key=lambda x: -x[1])))


if __name__ == "__main__":
    main()
