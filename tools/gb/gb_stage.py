#!/usr/bin/env python3
"""Writes a converted gun's game-side files into the repo: Scripts/Deagle/guns/<slug>.lua (clips + frame rates,
sound cues, gunshot sounds, muzzle / ejection bones, magazine timings), the guns index, the .cdf and .chrparams.
Prints the sound files to copy as 'SOUND <source relative path> <destination name>' lines.
usage: gb_stage.py <repo> <slug> <profile.json> <build.json> [times.json from tools/clip_times.py]"""
import sys, os, json, re
REPO, SLUG, PROF, BUILD = sys.argv[1:5]
prof, build = json.load(open(PROF)), json.load(open(BUILD))
ctimes = json.load(open(sys.argv[5])) if len(sys.argv) > 5 and os.path.exists(sys.argv[5]) else {}
NAME = f"{SLUG}_vm"
KEY = {"idle": "idle", "idle_empty": "idleEmpty", "draw": "draw", "draw_empty": "drawEmpty", "holster": "holster",
       "holster_empty": "holsterEmpty", "shoot": "shoot", "shoot_empty": "shootEmpty", "reload": "reload",
       "reload_empty": "reloadEmpty", "inspect": "inspect", "inspect_empty": "inspectEmpty",
       "shoot_add": "shootAdd", "shoot_empty_add": "shootEmptyAdd", "shoot_alt": "shootBurst",
       # Ready or Not ports (docs/ron/ron_grizzly_interactions.md): one clip each
       "draw_first": "drawFirst", "reload_speed": "reloadSpeed", "shoot_ads": "shootAds", "shoot_empty_ads": "shootEmptyAds",
       "reload_ads": "reloadAds", "reload_empty_ads": "reloadEmptyAds", "dry_fire": "dryFire", "low_up": "lowUp",
       "low_up_empty": "lowUpEmpty", "low_down": "lowDown", "low_down_empty": "lowDownEmpty",
       "sprint_start": "sprintStart", "sprint": "sprint", "sprint_stop": "sprintStop"}
CUES_FROM = {"draw_empty": "draw", "inspect_empty": "inspect"}   # derived clips reuse their source clip's sounds
sounds = {}
def snd(rel):
    if isinstance(rel, list):
        rel = rel[0] if rel else None
    if not rel:
        return None
    base = re.sub(r"[^A-Za-z0-9_.-]", "_", rel.rsplit("/", 1)[-1])
    sounds[rel] = base
    return f"guns/{SLUG}/{base}"
lua = lambda s: '"' + s.replace("\\", "/").replace('"', '') + '"'

anims, cues = [], []
clips = build["clips"]
shots = sorted([r for r in clips if re.fullmatch(r"shoot\d*", r)], key=lambda r: (len(r), r))
for role, c in sorted(clips.items()):
    if re.fullmatch(r"shoot\d+", role):
        continue
    if role not in KEY:
        continue
    entry = f'{{ {lua(c["name"])}, {c["frames"]}, {c["fps"]:g} }}'
    if role == "shoot_add":
        entry = "{ " + entry + " }"
    elif role == "shoot" and len(shots) > 1:
        entry = "{ " + ", ".join(f'{{ {lua(clips[s]["name"])}, {clips[s]["frames"]}, {clips[s]["fps"]:g} }}' for s in shots) + " }"
    elif role == "shoot":
        entry = "{ " + entry + " }"
    anims.append(f"\t\t{KEY[role]} = {entry},")
    pc = prof["clips"].get(CUES_FROM.get(role, role), {})
    lst = [(s["t"], snd(s["file"])) for s in pc.get("sounds", []) if s.get("file")]
    if lst and not role.startswith("shoot"):
        cues.append(f"\t\t{KEY[role]} = {{ " + ", ".join(f"{{ {t:.3f}, {lua(f)} }}" for t, f in lst) + " },")
shot_files = [snd(f) for f in prof.get("shotSounds", [])]
t = build.get("timing", {})
swap = {KEY[k]: v for k, v in t.get("swapTail", {}).items()}
bones = build.get("bones", {})
title = prof.get("title") or SLUG
src = prof.get("source") or {}
# Ready or Not's own events for this gun (played live by its engine in the plugin, docs/ron_live_spec.md)
ron = prof.get("ron") or {}
# fire modes the gun really has, when they differ from its CS2 counterpart's (CS2's Glock-18 has a burst a Glock 17 lacks)
modes_line = ("\tmodes = { " + ", ".join(lua(m) for m in prof["modes"]) + " },   -- fire modes (else its CS2 weapon's)\n") if prof.get("modes") else ""
# a Ready or Not gun: its handling numbers (guns/ron_stats.lua, tools/ron/ron_stats.py), its flash set ("large" = the
# Grizzly's V3, "small" = the G19's V2; else picked by the cartridge's blast) and its own casing model
ron_opt = "".join(f"\t{k} = {'true' if prof[k] is True else lua(prof[k])},{c}\n" for k, c in (
    ("ronStats", "   -- Ready or Not's handling numbers (guns/ron_stats.lua)"),
    ("ronOnly", "   -- only Ready or Not's sounds, whatever deagle_sounds says (sound.lua RonSounds)"),
    ("flashRon", "   -- Ready or Not flash set: large = V3 (Grizzly), small = V2 (G19)"),
    ("caseModel", "   -- its spent casing")) if prof.get(k))
ron_line = ("\tron = { " + ", ".join(f"{k} = {lua(v)}" for k, v in ron.items()) + " },   -- Ready or Not's events (its engine plays them)\n") if ron else ""
out = f'''-- {title}
-- generated by tools/gb/gb_stage.py from guns/{SLUG}.json (GameBanana {src.get("gamebanana", "?")}, {src.get("author", "?")}); private use only.
-- Edit the profile and re-run tools/gb/gb_convert.sh {SLUG}, not this file.
Deagle:RegisterGun({lua(SLUG)}, {{
	title = {lua(title)},
	short = {lua(prof.get("short") or SLUG.replace("_", " "))},
	magSize = {prof.get("magSize") or 15},
	cs2 = {lua(prof["cs2"]) if prof.get("cs2") else "nil"},
	cycle = {prof.get("fireInterval") or "nil"},   -- the mod's own seconds between shots (weapon script cycletime)
{modes_line}{ron_opt}	cdf = "objects/manmade/weapons/guns/{SLUG}/{NAME}.cdf",
	anims = {{   -- clip, frames, frames per second
{chr(10).join(anims)}
	}},
	cues = {{   -- seconds from clip start, sound file under Mods/deagle/sounds
{chr(10).join(cues)}
	}},
	shotSounds = {{ {", ".join(lua(f) for f in shot_files if f)} }},
{ron_line}	bones = {{ muzzle = {lua(bones.get("muzzle", "tag_flash"))}, brass = {lua(bones.get("brass", "tag_brass"))} }},
	rounds = {build.get("rounds", 0) or "false"},   -- rounds modelled in the magazine (attachments vm_round_1..)
	mags = {str(bool(build.get("mags"))).lower()},   -- magazines are their own attachments (vm_mag1, vm_mag2)
	swapTail = {{ {", ".join(f"{k} = {v}" for k, v in swap.items())} }},
	newMagAt = {t.get("newMagAt", "nil")},
	burstGap = {t.get("burstGap", "nil")},   -- seconds between burst rounds, from the burst clip's slide cycles
	-- clip-timeline seconds (tools/clip_times.py): clean reload cancel, new mag seated, ready to fire, settled
	times = {{ {", ".join(f"{k} = {{ " + ", ".join(f"{w} = {v}" for w, v in sorted(d.items())) + " }" for k, d in ctimes.items())} }},
}})
'''
gdir = os.path.join(REPO, "src", "Scripts", "Deagle", "guns")
os.makedirs(gdir, exist_ok=True)
open(os.path.join(gdir, f"{SLUG}.lua"), "w").write(out)
# the guns are the files that register one (guns/ also holds tables: cs2, calibers, armor, ron_stats...)
ids = sorted(f[:-4] for f in os.listdir(gdir) if f.endswith(".lua") and "Deagle:RegisterGun(" in open(os.path.join(gdir, f)).read())
open(os.path.join(gdir, "index.lua"), "w").write(
    "-- generated by tools/gb/gb_stage.py: every converted gun\nDeagle.gunIds = { " + ", ".join(lua(i) for i in ids) + " }\n")
odir = os.path.join(REPO, "src", "Objects", "manmade", "weapons", "guns", SLUG)
os.makedirs(odir, exist_ok=True)
# the magazines (hidden while a cancelled reload blends back) and one attachment per modelled round in the magazine
mags = "".join(f'\n    <Attachment Type="CA_SKIN" AName="vm_{m}" Binding="objects/manmade/weapons/guns/{SLUG}/{NAME}_{m}.skin" '
               f'Material="objects/manmade/weapons/guns/{SLUG}/{NAME}" Flags="0" />' for m in ("mag1", "mag2")) if build.get("mags") else ""
# one attachment per modelled round in the magazine (vm_round_1 = the top one)
rounds = "".join(f'\n    <Attachment Type="CA_SKIN" AName="vm_round_{i}" Binding="objects/manmade/weapons/guns/{SLUG}/{NAME}_round_{i}.skin" '
                 f'Material="objects/manmade/weapons/guns/{SLUG}/{NAME}" Flags="0" />' for i in range(1, build.get("rounds", 0) + 1))
# the mesh muzzle flash cards: skins of this gun on its muzzle bone (tools/flash_skin.sh builds them, tools/flash_cdf.py
# lists them; bone attachments drew the first card's model in KCD2)
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from flash_cdf import block as flash_block
flash = "".join("\n" + l for l in flash_block(REPO, f"src/Objects/manmade/weapons/guns/{SLUG}"))
open(os.path.join(odir, f"{NAME}.cdf"), "w").write(f'''<CharacterDefinition>
  <Model File="objects/manmade/weapons/guns/{SLUG}/{NAME}.chr" Material="objects/manmade/weapons/guns/{SLUG}/{NAME}" />
  <AttachmentList>
    <Attachment Type="CA_SKIN" AName="vm_mesh" Binding="objects/manmade/weapons/guns/{SLUG}/{NAME}_skin.skin" Material="objects/manmade/weapons/guns/{SLUG}/{NAME}" Flags="0" />{mags}{rounds}{flash}
  </AttachmentList>
</CharacterDefinition>
''')
open(os.path.join(odir, f"{NAME}.chrparams"), "w").write(f'''<Params>
  <AnimationList>
    <Animation name="#filepath" path="Animations/guns/{NAME}" />
    <Animation name="*" path="*.caf" />
  </AnimationList>
</Params>
''')
for rel, base in sounds.items():
    print(f"SOUND\t{rel}\t{base}")
print("STAGED", SLUG, len(anims), "clips,", len(cues), "cue lists,", len(shot_files), "shot sounds,", len(sounds), "sound files")
