#!/usr/bin/env python3
"""Generate src/Scripts/Deagle/guns/hitbones.lua: hit capsules on KCD2's male skeleton for exact bullet hit zones
(the living NPC's physics is one capsule, so rays always report mat_flesh / no part).

Capsules run along bone a -> bone b (runtime: entity:GetBonePos(a/b)); the ends sit at fractions t0..t1 of that
segment (may be < 0 or > 1). Radius and extent are fitted to the skeleton's ragdoll physics proxies (CompiledPhysicalProxies
in male.chr; convex hulls per bone), measured in bind pose: r = median distance of the hull vertices from the
segment, rMax = largest. Segments without a proxy (neck) are marked measured = false.

usage: gen_hitbones.py <copy of Objects/characters/humans/male/skeleton/male.chr (IPL_Characters-part3.pak)> [out.lua]"""
import os, statistics, struct, sys

# name, bone a, bone b, proxy bone (None = no proxy), fine zone, armor zone (KCD2 body_subpart -> body_part:
# head_neck -> head, hand_* -> arm_*, foot_* -> leg_*)
CAPSULES = [
    ("head",       "Head",          "HeadEnd",       "Head",          "head",      "head"),
    ("neck",       "Neck",          "Head",          None,            "neck",      "head"),
    ("chest",      "Spine3",        "Neck",          "Spine3",        "torso",     "torso"),
    ("belly",      "Spine",         "Spine3",        "Spine",         "torso",     "torso"),
    ("pelvis",     "LeftUpLeg",     "RightUpLeg",    "Hips",          "torso",     "torso"),
]
for s, S in (("left", "Left"), ("right", "Right")):
    CAPSULES += [
        ("shoulder_" + s, S + "Shoulder", S + "Arm",      S + "Shoulder", "arm_" + s,  "arm_" + s),
        ("upperarm_" + s, S + "Arm",      S + "ForeArm",  S + "Arm",      "arm_" + s,  "arm_" + s),
        ("forearm_" + s,  S + "ForeArm",  S + "Hand",     S + "ForeArm",  "arm_" + s,  "arm_" + s),
        ("hand_" + s,     S + "Hand",     S + "HandSlot", S + "Hand",     "hand_" + s, "arm_" + s),
        ("thigh_" + s,    S + "UpLeg",    S + "Leg",      S + "UpLeg",    "leg_" + s,  "leg_" + s),
        ("shin_" + s,     S + "Leg",      S + "Foot",     S + "Leg",      "leg_" + s,  "leg_" + s),
        ("foot_" + s,     S + "Foot",     S + "ToeBase",  S + "Foot",     "foot_" + s, "leg_" + s),
    ]
NECK_R = 0.06   # no proxy: guess from the head hull's lower width

def main():
    if len(sys.argv) < 2: sys.exit(__doc__)
    d = open(sys.argv[1], "rb").read()
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(repo, "src", "Scripts", "Deagle", "guns", "hitbones.lua")
    sig, ver, n, toff = struct.unpack_from("<4sIII", d, 0)
    chunks = {t: (sz, off) for t, v, cid, sz, off in (struct.unpack_from("<HHIII", d, toff + 16 * i) for i in range(n))}
    # CompiledBones 0x2000 (v0x800): 32-byte prefix, 584-byte records: ctrl, 2x BONE_PHYSICS (104), mass, W2B, B2W, name[256], limb, parent, ...
    sz, off = chunks[0x2000]
    bones = {}
    for i in range((sz - 32) // 584):
        b = off + 32 + 584 * i
        name = d[b + 312:b + 568].split(b"\0")[0].decode()
        bones[name] = dict(phys=struct.unpack_from("<i", d, b + 4)[0], b2w=struct.unpack_from("<12f", d, b + 264))
    # CompiledPhysicalProxies 0x2003: count, then { id, nPoints, nIdx, nMat, Vec3 points, u16 idx, u8 mat }
    sz, off = chunks[0x2003]
    cnt, = struct.unpack_from("<I", d, off); p = off + 4; prox = {}
    for _ in range(cnt):
        cid, npt, nidx, nmat = struct.unpack_from("<IIII", d, p); p += 16
        prox[cid] = [struct.unpack_from("<3f", d, p + 12 * i) for i in range(npt)]; p += 12 * npt + 2 * nidx + nmat
    pos = lambda nm: (bones[nm]["b2w"][3], bones[nm]["b2w"][7], bones[nm]["b2w"][11])
    def world(nm, q):
        m = bones[nm]["b2w"]
        return tuple(m[4 * r] * q[0] + m[4 * r + 1] * q[1] + m[4 * r + 2] * q[2] + m[4 * r + 3] for r in range(3))

    rows = []
    for cname, a, b, pb, zone, armor in CAPSULES:
        A, Bp = pos(a), pos(b)
        ab = [Bp[i] - A[i] for i in range(3)]; L2 = sum(x * x for x in ab); L = L2 ** 0.5
        if pb and bones[pb]["phys"] in prox:
            ts, ds = [], []
            for q in prox[bones[pb]["phys"]]:
                w = world(pb, q)
                t = sum((w[i] - A[i]) * ab[i] for i in range(3)) / L2
                c = [A[i] + t * ab[i] for i in range(3)]
                ts.append(t); ds.append(sum((w[i] - c[i]) ** 2 for i in range(3)) ** 0.5)
            r = statistics.median(ds); rmax = max(ds)
            t0, t1 = min(ts) + r / L, max(ts) - r / L
            if t0 > t1: t0 = t1 = (min(ts) + max(ts)) / 2
            measured = True
        else:
            r = rmax = NECK_R; t0, t1 = 0.0, 1.0; measured = False
        rows.append((cname, a, b, t0, t1, r, rmax, zone, armor, measured, L))

    f3 = lambda v: "%.3f" % v
    lines = ["-- GENERATED by tools/gen_hitbones.py from male.chr (ragdoll physics proxies); do not edit.",
             "-- Capsule from GetBonePos(a) + t0*(b-a) to GetBonePos(a) + t1*(b-a), radius r (median fit) / rMax (encloses the",
             "-- proxy hull). zone = fine zone, armor = the 6 armor zones (KCD2: neck->head, hand->arm, foot->leg).",
             "-- measured = false: no physics proxy, radius is a guess. See docs/kcd2_armor_hits.md (Hit zones from bones).",
             "Deagle = Deagle or {}",
             "Deagle.hitBones = {"]
    for cname, a, b, t0, t1, r, rmax, zone, armor, measured, L in rows:
        lines.append('\t{ name = "%s", a = "%s", b = "%s", t0 = %s, t1 = %s, r = %s, rMax = %s, zone = "%s", armor = "%s", measured = %s },  -- bind length %.3f m'
                     % (cname, a, b, f3(t0), f3(t1), f3(r), f3(rmax), zone, armor, "true" if measured else "false", L))
    lines.append("}")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as fh: fh.write("\n".join(lines) + "\n")
    print("hitbones.lua: %d capsules -> %s" % (len(rows), out))
    for row in rows: print("  %-14s %-14s -> %-13s t %.2f..%.2f r %.3f (max %.3f) %s" % (row[0], row[1], row[2], row[3], row[4], row[5], row[6], "" if row[9] else "GUESS"))

if __name__ == "__main__":
    main()
