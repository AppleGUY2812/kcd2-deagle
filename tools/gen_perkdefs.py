#!/usr/bin/env python3
"""Writes native/src/perkdefs.inc for deagle_respec (perkpoints.cpp, Claude 1): every perk that costs a perk point
(a level and visibility 2 in Libs/Tables/rpg/perk*.xml) with its skill or stat, and the sub-perks (metaperk_id) that
go with it. Run with the game's Data/Tables.pak:  python3 -I tools/gen_perkdefs.py <Tables.pak> native/src/perkdefs.inc"""
import re
import sys
import uuid
import zipfile

pak, out = sys.argv[1], sys.argv[2]
perks = {}
with zipfile.ZipFile(pak) as z:
    for name in sorted(z.namelist()):
        if re.fullmatch(r"Libs/Tables/rpg/perk[^/]*\.xml", name):
            for m in re.finditer(r"<perk [^>]*/>", z.read(name).decode("utf-8", "replace")):
                a = dict(re.findall(r'(\w+)="([^"]*)"', m.group(0)))
                if "perk_id" in a:
                    perks[a["perk_id"].lower()] = a
rows = []
for pid, a in sorted(perks.items(), key=lambda t: (t[1].get("perk_name", ""), t[0])):
    if not (a.get("level") and a.get("visibility") == "2"):
        continue
    if a.get("skill_selector"):
        kind, idx = 0, int(a["skill_selector"])
    elif a.get("stat_selector"):
        kind, idx = 1, int(a["stat_selector"])
    else:
        continue
    subs = sorted(k for k, b in perks.items() if b.get("metaperk_id", "").lower() == pid)
    rows.append((kind, idx, pid, a.get("perk_name", ""), subs))
with open(out, "w", newline="\n") as f:
    f.write("// generated by tools/gen_perkdefs.py from Libs/Tables/rpg/perk*.xml: perks that cost a point. Do not edit.\n")
    f.write("// { kind (0 skill, 1 stat), skill_id / stat index, perk GUID, sub-perk GUIDs removed with it }\n")
    for kind, idx, pid, name, subs in rows:
        sub = ", ".join(f'"{s}"' for s in subs)
        f.write(f'{{ {kind}, {idx}, "{pid}", {{ {sub} }} }},   // {name.strip()}\n')
print(len(rows), "point perks,", sum(len(r[4]) for r in rows), "sub-perks")
