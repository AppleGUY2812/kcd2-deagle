#!/usr/bin/env python3
"""Writes src/Libs/Particles/deagle_tracers.xml: one tracer effect per muzzle speed, every 25 m/s from 250 to 1000
(Lua picks the nearest: deagle_tracers.v<speed>). A tracer is one glowing particle that flies by itself like the round
it shows: the round's speed, real gravity, air drag fitted to our rounds, and it dies on the first thing it touches
(terrain, static or dynamic objects; e_ParticlesObjectCollisions is 2 in KCD2). Stretched along its motion
into a ~5 m streak (Ready or Not's tracer ribbon is up to 6.25 m), at least MinPixels wide at any range, glowing
white-orange like Ready or Not's (HDR 40,7,0 -> red), and dark for its first few metres (tracer compound lights once
out of the barrel). Lives as long as a round takes to fly cfg.range.
usage: gen_tracers.py <repo>"""
import math, os, sys

RANGE = 250.0            # m, Deagle.cfg.range: rounds are dropped past it (tests/run_ballistics.lua checks they match)
DRAG_LENGTH = 600.0      # m, our rounds' air-drag length (9 mm 567, .50 AE 691; ShotPhysics dragLength)
STREAK = 5.0             # m, streak length
IGNITE = 4.0             # m out of the barrel before it glows
SPEEDS = range(250, 1001, 25)

repo = sys.argv[1]
out = os.path.join(repo, "src", "Libs", "Particles", "deagle_tracers.xml")
rows = []
for v in SPEEDS:
    life = DRAG_LENGTH / v * (math.exp(RANGE / DRAG_LENGTH) - 1)   # time to fly RANGE with drag dv/dt = -v^2 / L
    k = v / DRAG_LENGTH                                            # linear drag (1/s) with the same start
    ignite = min(0.5, IGNITE / v / life)                           # share of the life spent dark
    stretch = STREAK / 2 / v                                       # s each way from the particle
    rows.append(
        f'\t<Particles Name="v{v}">\n'
        f'\t\t<Params Count="1" ParticleLifeTime="{life:.3f}" OrientToVelocity="true" BlendType="Additive"'
        f' Texture="textures/particles/spark_single_diff.tif"'
        f' Alpha="1,ParticleAge=(t={ignite:.4f};t={ignite * 1.6:.4f},v=1;t=0.9,v=1;t=1)"'
        f' Color="(x=1,y=0.62,z=0.32)" DiffuseLighting="0" DiffuseBacklighting="0" EmissiveLighting="15"'
        f' Size="0.006" Stretch="{stretch:.5f}" MinPixels="1.2" Speed="{v}" AirResistance="{k:.3f},WindScale=0"'
        f' GravityScale="1" PhysicsType="SimpleCollision" CollideTerrain="true" CollideStaticObjects="true"'
        f' CollideDynamicObjects="true" MaxCollisionEvents="1" FinalCollision="Die" />\n'
        f'\t</Particles>\n')
with open(out, "w", encoding="ascii", newline="\n") as fh:
    fh.write('<?xml version="1.0" encoding="us-ascii"?>\n')
    fh.write('<!-- generated by tools/gen_tracers.py: one tracer per muzzle speed (see the script for what each '
             'value means) -->\n')
    fh.write('<ParticleLibrary Name="deagle_tracers" SandboxVersion="1.0.0.0" ParticleVersion="28">\n')
    fh.write("".join(rows))
    fh.write("</ParticleLibrary>\n")
print(f"TRACERS {len(rows)} effects -> {out}")
