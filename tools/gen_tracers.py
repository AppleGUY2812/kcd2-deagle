#!/usr/bin/env python3
"""Writes src/Libs/Particles/deagle_tracers.xml and src/Libs/Particles/deagle_lab.xml.

deagle_tracers:
- trail (cfg.tracer.mode "trail", the default): the round's path drawn as it flies. Lua lays short pieces along every
  bit of path the round covers in a frame (Deagle:TrailAdd), so the streak is exactly where the round went: it starts
  at the muzzle, ends at what it hit, follows ricochets and wallbangs. One piece is a still, glowing streak DASH m long
  at scale 1 (barely moving, stretched along its own direction): a thin white-orange core held MinPixels wide at any
  range and a wider orange glow (Ready or Not's tracer is HDR (40,7,0) -> orange-red). It lives TRAIL_LIFE s: KCD2
  draws a new emitter a frame or two late and pre-ages it a frame (MODLOG), so shorter pieces were never seen; it
  fades over the second half, so the streak tapers off behind the round.
- v<speed> (cfg.tracer.mode "flying"): one particle per muzzle speed, every 25 m/s from 250 to 1000, that flies by
  itself like the round (speed, gravity, drag fitted to our rounds) and dies on the first thing it touches. Stretched
  into a ~5 m streak, dark for its first few metres. Not seen in game on 2026-10-12 (tests/LAB below).

deagle_lab: variants for a live look (Deagle lab snippets, docs/DEBUG.md): the 250 m/s tracer as built, and the same
with one thing changed each, so the one that draws shows what kept it from drawing; the trail piece long-lived; two
camera-facing quads (which axis Aspect stretches).
usage: gen_tracers.py <repo>"""
import math, os, sys

RANGE = 250.0            # m, Deagle.cfg.range: rounds are dropped past it (tests/run_ballistics.lua checks they match)
DRAG_LENGTH = 600.0      # m, our rounds' air-drag length (9 mm 567, .50 AE 691; ShotPhysics dragLength)
STREAK = 5.0             # m, flying streak length
IGNITE = 4.0             # m out of the barrel before a flying tracer glows
SPEEDS = range(250, 1001, 25)
DASH = 1.0               # m, a trail piece at scale 1 (Deagle.cfg.tracer.dash matches; tests check)
TRAIL_LIFE = 0.12        # s a trail piece lives
SPARK = "textures/particles/spark_single_diff.tif"


def attrs(d):
    return " ".join(f'{k}="{v}"' for k, v in d.items())


def flying(v):
    life = DRAG_LENGTH / v * (math.exp(RANGE / DRAG_LENGTH) - 1)   # time to fly RANGE with drag dv/dt = -v^2 / L
    k = v / DRAG_LENGTH                                            # linear drag (1/s) with the same start
    ignite = min(0.5, IGNITE / v / life)                           # share of the life spent dark
    stretch = STREAK / 2 / v                                       # s each way from the particle
    return {
        "Count": "1", "ParticleLifeTime": f"{life:.3f}", "OrientToVelocity": "true", "BlendType": "Additive",
        "Texture": SPARK, "Alpha": f"1,ParticleAge=(t={ignite:.4f};t={ignite * 1.6:.4f},v=1;t=0.9,v=1;t=1)",
        "Color": "(x=1,y=0.62,z=0.32)", "DiffuseLighting": "0", "DiffuseBacklighting": "0", "EmissiveLighting": "15",
        "Size": "0.006", "Stretch": f"{stretch:.5f}", "MinPixels": "1.2", "Speed": f"{v}",
        "AirResistance": f"{k:.3f},WindScale=0", "GravityScale": "1", "PhysicsType": "SimpleCollision",
        "CollideTerrain": "true", "CollideStaticObjects": "true", "CollideDynamicObjects": "true",
        "MaxCollisionEvents": "1", "FinalCollision": "Die",
    }


def piece(life, fade=True):
    # a still streak DASH m long: it creeps at 1 m/s along its direction and is stretched DASH / 2 s each way
    alpha = "ParticleAge=(v=1;t=0.45,v=1;t=1)" if fade else "1"
    base = {"Count": "1", "ParticleLifeTime": f"{life}", "OrientToVelocity": "true", "BlendType": "Additive",
            "Texture": SPARK, "DiffuseLighting": "0", "DiffuseBacklighting": "0", "Speed": "1",
            "Stretch": f"{DASH / 2:.3f}", "AirResistance": "WindScale=0", "GravityScale": "0"}
    core = dict(base, Alpha=f"1,{alpha}" if fade else "1", Color="(x=1,y=0.78,z=0.5)", EmissiveLighting="30",
                Size="0.004", MinPixels="1.2", SortOffset="1")
    glow = dict(base, Alpha=f"0.35,{alpha}" if fade else "0.35", Color="(x=1,y=0.32,z=0.06)", EmissiveLighting="10",
                Size="0.012", MinPixels="4")
    return [("core", core), ("glow", glow)]


def effect(name, params=None, childs=None):
    out = [f'\t<Particles Name="{name}">']
    if childs:
        out += ['\t\t<Params Enabled="false" Count="1" ParticleLifeTime="0.05" />', "\t\t<Childs>"]
        for cn, cp in childs:
            out += [f'\t\t\t<Particles Name="{cn}">', f"\t\t\t\t<Params {attrs(cp)} />", "\t\t\t</Particles>"]
        out += ["\t\t</Childs>"]
    else:
        out += [f"\t\t<Params {attrs(params)} />"]
    out += ["\t</Particles>"]
    return "\n".join(out) + "\n"


def library(path, name, comment, effects):
    with open(path, "w", encoding="ascii", newline="\n") as fh:
        fh.write('<?xml version="1.0" encoding="us-ascii"?>\n')
        fh.write(f"<!-- generated by tools/gen_tracers.py: {comment} -->\n")
        fh.write(f'<ParticleLibrary Name="{name}" SandboxVersion="1.0.0.0" ParticleVersion="28">\n')
        fh.write("".join(effects))
        fh.write("</ParticleLibrary>\n")


def drop(d, *keys):
    return {k: v for k, v in d.items() if k not in keys}


def main(repo):
    pdir = os.path.join(repo, "src", "Libs", "Particles")
    tracers = [effect("trail", childs=piece(TRAIL_LIFE))] + [effect(f"v{v}", flying(v)) for v in SPEEDS]
    library(os.path.join(pdir, "deagle_tracers.xml"), "deagle_tracers",
            "the trail piece and one flying tracer per muzzle speed (see the script for what each value means)", tracers)

    ref = flying(250)
    quad = {"Count": "1", "ParticleLifeTime": "1.5", "Facing": "CameraX", "OrientToVelocity": "true",
            "BlendType": "Additive", "Texture": SPARK, "Color": "(x=1,y=0.62,z=0.32)", "DiffuseLighting": "0",
            "EmissiveLighting": "15", "Speed": "0.01", "AirResistance": "WindScale=0", "GravityScale": "0"}
    lab = [
        effect("t_ref", ref),
        effect("t_nocoll", drop(ref, "PhysicsType", "CollideTerrain", "CollideStaticObjects", "CollideDynamicObjects",
                                "MaxCollisionEvents", "FinalCollision")),
        effect("t_big", dict(drop(ref, "MinPixels"), Size="0.03")),
        effect("t_nostretch", drop(ref, "Stretch")),
        effect("t_alpha1", dict(ref, Alpha="1")),
        effect("t_slow", dict(ref, Speed="20", AirResistance="WindScale=0")),
        effect("t_free", dict(ref, Facing="Free")),
        effect("trail_long", childs=piece(1.5, fade=False)),
        effect("quad_long", dict(quad, Size="0.005", Aspect="100", MinPixels="1.2")),   # long if Aspect stretches along the motion
        effect("quad_wide", dict(quad, Size="0.5", Aspect="0.01")),                     # long if Aspect squashes along it
    ]
    library(os.path.join(pdir, "deagle_lab.xml"), "deagle_lab", "variants to look at live (see the script)", lab)
    print(f"TRACERS trail + {len(SPEEDS)} flying, LAB {len(lab)} effects")


if __name__ == "__main__":
    main(sys.argv[1])
