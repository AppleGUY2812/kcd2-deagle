#!/usr/bin/env python3
"""Ready or Not's handling numbers for the guns we import from it -> src/Scripts/Deagle/guns/ron_stats.lua
(Deagle.ronStats["<RoN blueprint>"] = { <RoN property> = value, ... }), as decoded from the weapon blueprints by
tools/ron/ronrecoil.py (docs/ron/ron_recoil.json: the base game's WeaponsRevised; docs/ron/ron_recoil_dlc3.json: the
DLC3 Grizzly). A gun file points at its row with ronStats = "<blueprint>", the way cs2 = "weapon_x" points at
guns/cs2.lua. Names and values stay Ready or Not's own (1:1); recoil.lua / motion.lua / viewmodel.lua turn them into
our kicks. A property the blueprint doesn't set is the C++ class default: those are listed in DEFAULTS with where
each was read (docs/ron/ron_recoil_code.md), never guessed.
    python3 -I tools/ron/ron_stats.py [<repo>]
"""
import json, os, re, struct, sys

REPO = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..")
SOURCES = ["docs/ron/ron_recoil.json", "docs/ron/ron_recoil_dlc3.json"]
GUNS = ["BP_Secondary_LARGrizzly"]   # the imported ones (the G19 joins when it's imported)
KEEP = re.compile(r"^(Recoil|ADS|FirstShot|Velocity|bCalculateProcRecoil|MeshspaceTransform_|MeshSpaceAimInterp|Inertia"
                  r"|MovementSpeed|LazySpring|FreeAim|Spread|BulletsFiredUntilFullyAccurate|FireRate$|Capacity$"
                  r"|FireCameraShake$|ShellMesh$|ItemWeight$|AvailableFireModes$|AmmoMax$)")
# C++ class defaults (BaseWeapon ctor FUN_1449ac070, docs/ron/ron_recoil_code.md section 0), for what a blueprint doesn't set
DEFAULTS = {
    "RecoilInterpSpeed": 10.0, "ADSRecoilMultiplier": 1.0, "RecoilReturnRate": 10.0, "FirstShotRecoil": 0.7,
    "FirstShotSpread": 0.1, "FirstShotResetTime": 0.2, "VelocityRecoilMultiplier": 0.005, "RecoilMultiplierPitch": 0.0,
    "RecoilMultiplierYaw": 0.0, "RecoilReturnPercentage": 0.9, "RecoilReturnInterpSpeed": 2.5, "bCalculateProcRecoil": False,
    "RecoilDampStrength": 7.5, "RecoilFireTime": 0.05, "RecoilFireStrength": 0.5, "RecoilFireStrengthFirst": 3.0,
    "RecoilAngleStrength": 0.4, "RecoilRandomness": 0.1, "RecoilFireADSModifier": 0.7, "RecoilAngleADSModifier": 0.3,
    "RecoilRotationBuildup": [0.0, 0.0, 0.0], "RecoilPositionBuildup": [0.0, 0.0, 0.0], "RecoilBuildupADSModifier": 0.0,
    "RecoilHasBuildup": False, "RecoilBuildupDampStrength": 15.0,
}
# the fire camera shakes the guns use (LegacyCameraShake assets, DATA in docs/ron/ron_recoil_code.md 5.2): duration,
# blend in / out (s), then per axis { amplitude, frequency (rad/s), random phase (true) or 0 }: rotation pitch / yaw /
# roll (deg), location forward / right / up (cm), FOV (deg)
SHAKES = {
    "C_Generic_Fire_Grizzly_C": {"Duration": 0.2, "BlendIn": 0.0, "BlendOut": 0.5,
        "Rot": [[14.0, 18.0, True], [0.0, 0.0, False], [8.8, 16.0, True]],
        "Loc": [[8.0, 32.0, True], [0.25, 25.0, True], [4.0, 13.0, False]], "FOV": [1.5, 10.0, True]},
}
# the player's side (BasePlayer DATA P / PlayerCharacter CODE, docs/ron/ron_recoil_code.md 3, 6): the camera kick's
# rate (/s), the gun offset's interp (8 x 0.8 /s), its clamps (cm, component: right, forward, up), the pending kick's
# push on the gun offset (MeshspaceRecoilMovementMultiplier / MinMax, MeshSpaceMovementMultiplier1P, the ADS terms)
PLAYER = {"KickRate": 7.0, "MeshInterp": 6.4, "OffsetMin": [-10.0, 2.0, -10.0], "OffsetMax": [10.0, 10.0, 10.0],
          "KickMove": [2.0, 2.0, 2.0], "KickMoveMax": [2.0, 2.0, 2.0], "MoveMul1P": 0.5, "AdsKickBack": 2.5, "AdsKickBackMax": 2.5}


def quat(hexstr):
    """UE5 FQuat as cooked: four little-endian doubles x, y, z, w."""
    x, y, z, w = struct.unpack("<4d", bytes.fromhex(hexstr))
    return {"x": x, "y": y, "z": z, "w": w}


def value(v):
    if isinstance(v, dict):
        return {k: (quat(x) if k == "Rotation" and isinstance(x, str) and len(x) == 64 else value(x)) for k, x in v.items()}
    if isinstance(v, list):
        return [value(x) for x in v]
    return v


def lua(v, ind="\t\t"):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(float(v)).rstrip("0").rstrip(".") if isinstance(v, float) else str(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "/").replace('"', "") + '"'
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x, ind) for x in v) + " }"
    return "{ " + ", ".join(f"{k} = {lua(x, ind)}" for k, x in v.items()) + " }"


rows = {}
for src in SOURCES:
    rows.update(json.load(open(os.path.join(REPO, src))))
out = ["-- generated by tools/ron/ron_stats.py from " + " + ".join(SOURCES) + ": Ready or Not's own handling numbers,",
       "-- 1:1 (its property names and units: degrees, cm, seconds). Re-run the tool; don't edit this file.",
       "Deagle.ronStats = Deagle.ronStats or {}"]
for gun in GUNS:
    props = rows[gun]["props"]
    keep = {k: value(v) for k, v in props.items() if KEEP.match(k)}
    for k, v in DEFAULTS.items():
        keep.setdefault(k, v)
    out.append(f'Deagle.ronStats["{gun}"] = {{   -- parent {rows[gun]["super"]}')
    for k in sorted(keep):
        out.append(f"\t{k} = {lua(keep[k])},")
    out.append("}")
out.append("Deagle.ronShakes = {")
for k, v in SHAKES.items():
    out.append(f'\t["{k}"] = {lua(v)},')
out.append("}")
out.append("Deagle.ronPlayer = " + lua(PLAYER))
path = os.path.join(REPO, "src/Scripts/Deagle/guns/ron_stats.lua")
open(path, "w", newline="\n").write("\n".join(out) + "\n")
print(path, sum(1 for l in out if l.startswith("\t")), "values")
