#!/usr/bin/env python3
"""Evens out the gunshot samples before physics sets each gun's loudness (docs/handling-physics-design.md, section 6):
every gun's shot files are measured (loudest 50 ms, the blast) and get a gain that brings them to one reference level,
written to src/Scripts/Deagle/guns/shot_gain.lua. Gains stay <= 1 (FMOD gains above 1 can clip). Fails if a shot sound
a gun uses can't be measured.
usage: shot_loudness.py <repo>"""
import glob, math, os, re, sys, wave
import numpy as np

repo = sys.argv[1]
sounds = os.path.join(repo, "assets", "build", "sounds")
REF_DB = -12.0                       # every blast is brought down to this (dBFS, loudest 50 ms)

files = [f"decho_orig/decho-{i}.wav" for i in range(1, 9)]     # the Deagle's own (MWII) shots: deagle_main.lua origShots
for lua in glob.glob(os.path.join(repo, "src", "Scripts", "Deagle", "guns", "*.lua")):
    m = re.search(r"shotSounds\s*=\s*\{([^}]*)\}", open(lua, encoding="utf-8").read())
    if m:
        files += re.findall(r'"([^"]+\.wav)"', m.group(1))

def blast_db(path):
    w = wave.open(path)
    n, ch, sw, sr = w.getnframes(), w.getnchannels(), w.getsampwidth(), w.getframerate()
    raw = w.readframes(n); w.close()
    if sw != 2:
        raise SystemExit(f"{path}: {sw * 8}-bit, only 16-bit is measured")
    x = (np.frombuffer(raw, np.int16).astype(float) / 32768).reshape(-1, ch).mean(axis=1)
    win = int(0.05 * sr)
    e = np.convolve(x * x, np.ones(win) / win, mode="valid")
    return 10 * math.log10(e.max() + 1e-12)

gains, bad = {}, []
for f in sorted(set(files)):
    p = os.path.join(sounds, f)
    if not os.path.exists(p):
        bad.append(f); continue
    db = blast_db(p)
    gains[f] = round(min(1.0, 10 ** ((REF_DB - db) / 20)), 4)
if bad:
    print("SHOT LOUDNESS missing files:", " ".join(bad)); sys.exit(1)
# Ready or Not MK V sets per place (docs/mk5_sound_spec.md): ONE gain for all of them, the one that brings the outdoor
# forest set (the default) to the reference, so the indoor sets stay louder than outdoor, as in Ready or Not
mk5 = sorted(glob.glob(os.path.join(sounds, "mk5", "*", "shot-*.wav")))
if mk5:
    forest = [p for p in mk5 if os.sep + "out_forest" + os.sep in p]
    if not forest:
        raise SystemExit("SHOT LOUDNESS: mk5 sets without out_forest")
    db = float(np.median([blast_db(p) for p in forest]))
    g = round(min(1.0, 10 ** ((REF_DB - db) / 20)), 4)
    for p in mk5:
        gains[os.path.relpath(p, sounds).replace(os.sep, "/")] = g
out = os.path.join(repo, "src", "Scripts", "Deagle", "guns", "shot_gain.lua")
with open(out, "w") as fh:
    fh.write("-- generated by tools/shot_loudness.py: per-file gain bringing each gunshot's blast to %.0f dBFS (loudest 50 ms)\n" % REF_DB)
    fh.write("Deagle.shotGain = {\n")
    for f, g in gains.items():
        fh.write(f'\t["{f}"] = {g},\n')
    fh.write("}\n")
print(f"SHOT LOUDNESS {len(gains)} files -> {out}")
